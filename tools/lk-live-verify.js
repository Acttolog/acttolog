#!/usr/bin/env node
/*
 * Loksewa publish verification — compares what is actually served against the
 * files that were generated locally, so a stale cache or a truncated upload
 * cannot pass as success.
 *
 *   node tools/lk-live-verify.js https://acttolog.github.io
 */
const fs = require('node:fs');
const path = require('node:path');
const https = require('node:https');
const http = require('node:http');

const BASE = (process.argv[2] || 'https://acttolog.github.io').replace(/\/$/, '');
const DL = path.join(__dirname, '..', 'public', 'loksewa', 'dl');
const papers = require('../src/lib/content/loksewa.json').papers.map((p) => p.slug);
const DOCS = [...papers, 'full', 'planner', 'laws', 'practice'];

let pass = 0;
const fails = [];
const check = (ok, name, detail = '') => {
  if (ok) { pass++; console.log(`  ok  ${name}`); }
  else { fails.push(`${name}${detail ? ' — ' + detail : ''}`); console.log(`FAIL  ${name}${detail ? ' — ' + detail : ''}`); }
};

const req = (urlPath, method = 'GET') =>
  new Promise((r) => {
    const mod = BASE.startsWith('https') ? https : http;
    const u = new URL(BASE + urlPath);
    const q = mod.request(
      { host: u.hostname, port: u.port || (mod === https ? 443 : 80), path: u.pathname + u.search, method,
        headers: { 'User-Agent': 'acttolog-lk-verify', 'Cache-Control': 'no-cache' } },
      (res) => {
        const chunks = [];
        res.on('data', (d) => chunks.push(d));
        res.on('end', () => r({ s: res.statusCode, h: res.headers, b: Buffer.concat(chunks) }));
      },
    );
    q.on('error', (e) => r({ s: 0, h: {}, b: Buffer.from(e.message) }));
    q.setTimeout(45000, () => { q.destroy(); r({ s: 0, h: {}, b: Buffer.from('timeout') }); });
    q.end();
  });

(async () => {
  console.log(`\nLOKSEWA PUBLISH VERIFICATION — ${BASE}\n`);

  console.log('PAGES');
  for (const p of ['/loksewa', '/loksewa/downloads', '/loksewa/explorer']) {
    const r = await req(p);
    const html = r.b.toString('utf8');
    check(r.s === 200 && html.includes('<!DOCTYPE html>'), `${p} serves HTML`, `status ${r.s}`);
  }
  for (const d of DOCS) {
    const r = await req(`/loksewa/print/${d}`);
    const html = r.b.toString('utf8');
    check(r.s === 200 && html.includes('lkdoc'), `/loksewa/print/${d} serves the document`, `status ${r.s}`);
  }

  console.log('\nDOWNLOAD ASSETS — served bytes must equal generated bytes');
  const names = fs.readdirSync(DL).filter((f) => !f.startsWith('.'));
  let served = 0;
  for (const n of names) {
    const local = fs.statSync(path.join(DL, n)).size;
    const r = await req(`/loksewa/dl/${n}`, 'HEAD');
    const remote = Number(r.h['content-length'] || 0);
    const type = r.h['content-type'] || '';
    const want = n.endsWith('.pdf') ? 'application/pdf' : n.endsWith('.mp4') ? 'video/mp4' : 'image/jpeg';
    check(r.s === 200 && remote === local && type.includes(want), `${n}`, `${r.s} · ${remote}/${local} bytes · ${type}`);
    served += remote;
  }
  check(names.length === 10, 'exactly 10 public download assets', String(names.length));
  console.log(`  served download total: ${(served / 1048576).toFixed(2)} MB`);

  console.log('\nPAID MATERIAL MUST NOT BE PUBLIC');
  for (const p of papers) {
    const r = await req(`/loksewa/dl/slides-${p}.pptx`, 'HEAD');
    check(r.s === 404, `slides-${p}.pptx is not downloadable`, `status ${r.s}`);
  }
  const paidLeak = names.filter((n) => n.endsWith('.pptx'));
  check(paidLeak.length === 0, 'no pptx inside the published download folder', paidLeak.join(','));

  console.log('\nOFFERS');
  // The content merge drops an extension offer when a seed offer reuses its id,
  // so every published offer from both sources must still resolve.
  const seed = require('../src/lib/content/seed.json');
  const ext = require('../src/lib/content/extensions.json');
  const merged = [...seed.offers];
  for (const o of ext.newOffers || []) if (!merged.some((x) => x.id === o.id)) merged.push(o);
  const ids = merged.map((o) => o.id);
  check(ids.length === new Set(ids).size, 'no offer id collisions between seed and extensions');
  for (const o of ext.newOffers || []) {
    check(merged.some((x) => x.slug === o.slug), `extension offer ${o.slug} survived the merge`);
  }
  const published = merged.filter((o) => o.status === 'published' || o.status === 'scheduled');
  for (const o of published) {
    const r = await req(`/offers/${o.slug}`);
    check(r.s === 200, `/offers/${o.slug}`, `status ${r.s}`);
  }
  console.log(`  published offers checked: ${published.length}`);

  console.log('\nSITEMAP');
  const sm = await req('/sitemap.xml');
  const xml = sm.b.toString('utf8');
  const urls = (xml.match(/<loc>/g) || []).length;
  check(sm.s === 200 && urls >= 92, `sitemap lists ${urls} URLs`, `status ${sm.s}`);
  check(xml.includes('/loksewa/downloads'), 'sitemap includes the download centre');
  check(xml.includes('/loksewa/explorer'), 'sitemap includes the explorer');
  check(!xml.includes('/loksewa/print/'), 'print routes stay out of the sitemap');
  check(xml.includes('https://acttolog.github.io'), 'sitemap uses the live origin');

  console.log('\nDOWNLOAD CENTRE COPY');
  const dc = await req('/loksewa/downloads');
  const body = dc.b.toString('utf8');
  check(body.includes('जम्मा डाटा:'), 'closing total line is the edited copy');
  check(!body.includes('सामग्री संकलन:'), 'redundant prefix is gone');
  check(/३००/.test(body) && /६००/.test(body), 'both price points are present');
  check(body.includes('orientation.mp4'), 'the orientation film is referenced');

  console.log(`\n${pass} passed, ${fails.length} failed`);
  if (fails.length) { console.log('\nFAILURES:'); for (const f of fails) console.log(' - ' + f); process.exitCode = 1; }
})();